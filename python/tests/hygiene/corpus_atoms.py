def atom(*index: int) -> str:
    """The piece at each position, joined."""
    return "".join(FRAGMENTS[i] for i in index)


def _group(*atoms: tuple[int, ...]) -> tuple[str, ...]:
    return tuple(atom(*positions) for positions in atoms)


